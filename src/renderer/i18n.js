  let current = 'zh-CN';

  function t(key, fallback) {
    const pack = PACKS[current] || PACKS['zh-CN'];
    const v = pack[key];
    if (v != null && v !== '') return v;
    const zh = PACKS['zh-CN'][key];
    if (zh != null && zh !== '') return zh;
    return fallback != null ? fallback : key;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      const val = t(key, el.dataset.i18nFallback || el.textContent.trim());
      if (el.childElementCount === 0) el.textContent = val;
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh, el.placeholder);
    });
  }

  function setLang(lang) {
    current = PACKS[lang] ? lang : 'zh-CN';
    document.documentElement.lang = current;
    apply();
    return current;
  }

  window.I18N = {
    t,
    apply,
    setLang,
    get lang() {
      return current;
    },
    languages: Object.keys(PACKS),
  };
